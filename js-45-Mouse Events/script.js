//mouseenter vs mouseover
// mouseenter: fires when the mouse pointer enters the element
// mouseover: fires when the mouse pointer enters the element or any of its child elements

//mouseleave vs mouseout
// mouseleave: fires when the mouse pointer leaves the element
// mouseout: fires when the mouse pointer leaves the element or any of its child elements